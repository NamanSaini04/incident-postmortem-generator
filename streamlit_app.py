"""Dashboard for the Cybersecurity Incident Postmortem Generator (Phase 10).

Run locally:   streamlit run streamlit_app.py
Demo mode (default) shows saved reports and costs nothing. Live generation appears
only when PMGEN_LIVE=1 and ANTHROPIC_API_KEY are set on your own machine.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "src"))  # works without installing the package

import plotly.express as px  # noqa: E402
import streamlit as st  # noqa: E402

from pmgen import dashboard_data as dd  # noqa: E402
from pmgen.postmortem import fmt_duration, render_markdown  # noqa: E402
from pmgen.samples import find_data_dir, list_incidents  # noqa: E402
from pmgen.verify import render as render_verify  # noqa: E402

st.set_page_config(page_title="Incident Postmortem Generator", layout="wide")

INCIDENTS = find_data_dir()
# Chart colours, readable on the dark theme in .streamlit/config.toml. Exact = blue, estimated = amber/violet.
BASIS_COLOURS = {"exact": "#38BDF8", "date inferred": "#F59E0B", "timezone assumed": "#A78BFA"}
TIMING_COLOURS = {"exact": "#38BDF8", "approximate (inferred time)": "#F59E0B"}


@st.cache_data(show_spinner=False)
def _reports(folder: str) -> dict[str, str]:
    return {k: v.model_dump_json() for k, v in dd.load_reports(Path(folder)).items()}


def _bundle(pm_json: str) -> dd.Bundle:
    from pmgen.schemas import Postmortem
    return dd.load_bundle(Postmortem.model_validate_json(pm_json), INCIDENTS)


# ---------------------------------------------------------------- sidebar
st.sidebar.title("Postmortem Generator")
st.sidebar.caption("Defensive use only. Synthetic incidents. Every claim cites its evidence.")
reports_dir = dd.find_reports_dir()
reports = _reports(str(reports_dir))

if dd.live_generation_enabled():
    st.sidebar.divider()
    st.sidebar.subheader("Live generation (local)")
    target = st.sidebar.selectbox("Incident evidence", list_incidents())
    st.sidebar.caption("Calls the Anthropic API: about $0.12 per run.")
    if st.sidebar.button("Generate new report"):
        from pmgen.evidence_pack import build_pack
        from pmgen.ingest import ingest_folder
        from pmgen.llm import AnthropicClient
        from pmgen.postmortem import generate
        with st.spinner("Generating and validating (1-3 minutes)..."):
            pm = generate(build_pack(ingest_folder(INCIDENTS / target)), AnthropicClient())
        reports = {**reports, pm.incident_id: pm.model_dump_json()}
        st.session_state["live"] = {pm.incident_id: pm.model_dump_json()}
        st.sidebar.success(f"Generated {pm.incident_id}. Not saved to disk.")
reports = {**reports, **st.session_state.get("live", {})}

if not reports:
    st.error(f"No saved reports found in `{reports_dir}`. Copy `*_postmortem.json` files there, "
             "or set PMGEN_REPORTS_DIR.")
    st.stop()

choice = st.sidebar.radio("Incident", sorted(reports), format_func=lambda i: i)
b = _bundle(reports[choice])
pm = b.report
st.sidebar.divider()
st.sidebar.markdown(f"**Verifier:** {'PASS' if b.check.ok else 'FAIL'} "
                    f"({sum(c.checked for c in b.check.checks)} items)")
st.sidebar.caption(f"Reports from `{reports_dir.name}`. Mode: "
                   f"{'live + demo' if dd.live_generation_enabled() else 'demo (saved reports, no API calls)'}")

# ---------------------------------------------------------------- header
st.title(pm.title)
st.caption(f"{pm.incident_id} · {pm.category.value.replace('_', ' ')} · "
           f"generated {pm.generated_at:%Y-%m-%d} by {pm.model}")
st.warning("DRAFT: requires human review. Generated by code plus an LLM from synthetic evidence.", icon="⚠️")
ov = dd.overview(pm)
c = st.columns(4)
c[0].metric("Severity", pm.severity.value)
c[1].metric("Confidence", ov["Classification confidence"])
c[2].metric("ATT&CK techniques", len(pm.attack))
c[3].metric("Verifier", "PASS" if b.check.ok else "FAIL")

# Tables of sentences use st.table (wraps text); long record lists keep st.dataframe (scrolls).
tabs = st.tabs(["Overview", "Timeline", "Evidence", "ATT&CK", "Root cause", "Impact & response",
                "Actions", "Report", "Verification"])

with tabs[0]:
    st.subheader("Executive summary")
    st.write(pm.executive_summary)
    st.caption(f"Severity rationale: {pm.severity_rationale}")
    left, right = st.columns(2)
    left.table([{"field": k, "value": v} for k, v in ov.items()])
    if b.score:
        right.markdown("**Scored against the hidden answer key**")
        right.table(dd.score_rows(b.score))
        right.caption("The model never sees the answer key. Synthetic data, one run per incident.")

with tabs[1]:
    rows = dd.timeline_rows(pm)
    st.caption("Built by code from the evidence, not by the LLM. Hover a point for the event and its source.")
    if rows:
        fig = px.scatter(rows, x="time", y="source", color="time_basis", symbol="kind",
                         color_discrete_map=BASIS_COLOURS,
                         symbol_map={"response milestone": "star", "key event": "diamond", "other event": "circle"},
                         hover_data={"event_id": True, "event": True, "milestone": True, "cited_at": True,
                                     "kind": False})
        fig.update_traces(marker_size=13)
        fig.update_layout(height=380, yaxis_title=None, xaxis_title="time (UTC)", legend_title=None)
        st.plotly_chart(fig, use_container_width=True)
    st.dataframe([{k: r[k] for k in ("event_id", "time", "event", "cited_at", "time_basis", "milestone")}
                  for r in rows], use_container_width=True, hide_index=True)

with tabs[2]:
    ev = dd.evidence_rows(pm, b.evidence_dir)
    files = sorted({r["file"] for r in ev})
    pick = st.multiselect("Files", files, default=files)
    only = st.checkbox("Only records cited by the report")
    shown = [r for r in ev if r["file"] in pick and (not only or r["cited_by_claims"])]
    st.caption(f"{len(ev)} records; {dd.uncited_share(ev):.0%} are not cited by any claim.")
    st.dataframe(shown, use_container_width=True, hide_index=True)
    st.markdown("**Indicators of compromise** (only values found in the evidence; nothing invented)")
    st.dataframe([{"indicator": i.value, "type": i.entity_type.value,
                   "first seen": f"{i.first_seen.file} {i.first_seen.locator}"} for i in pm.indicators],
                 use_container_width=True, hide_index=True)

with tabs[3]:
    st.caption(f"IDs and names checked against {pm.attack_catalog or 'the bundled catalogue'}.")
    st.table(dd.attack_rows(pm))

with tabs[4]:
    if pm.immediate_cause:
        st.markdown(f"**Immediate cause** `[{pm.immediate_cause.certainty.value}]`  \n{pm.immediate_cause.statement}")
    if pm.root_cause:
        st.markdown(f"**Root cause** `[{pm.root_cause.certainty.value}]`  \n{pm.root_cause.statement}")
    st.markdown("**Contributing factors**")
    st.table(dd.finding_rows(pm.contributing_factors))
    st.markdown("**Detection gaps**")
    st.table(dd.finding_rows(pm.detection_gaps))

with tabs[5]:
    l, r = st.columns(2)
    l.markdown("**Impact**")
    l.table([{"area": "Systems involved", "assessment": ov["Systems involved"]},
             {"area": "Accounts involved", "assessment": ov["Accounts involved"]}] +
            [{"area": n, "assessment": f"[{f.certainty.value}] {f.statement}" if f else "not assessed"}
             for n, f in (("Data affected", pm.impact.data_affected),
                          ("Operational", pm.impact.operational_impact),
                          ("Business", pm.impact.business_impact))])
    r.markdown("**Response timing** (computed by code from timestamps)")
    dur = dd.duration_rows(pm)
    if dur:
        fig = px.bar(dur, x="minutes", y="measure", orientation="h", color="timing",
                     color_discrete_map=TIMING_COLOURS,
                     hover_data=["from_to"], text=[fmt_duration(d["seconds"]) for d in dur])
        fig.update_layout(height=300, yaxis_title=None, legend_title=None)
        r.plotly_chart(fig, use_container_width=True)
        r.caption("Approximate = an endpoint's date was inferred or its timezone assumed.")
    else:
        r.info("Not computed for this report.")

with tabs[6]:
    st.table(dd.action_rows(pm))
    st.markdown("**Lessons learned**")
    st.table([{"area": x.area, "lesson": x.lesson} for x in pm.lessons])
    st.markdown("**Open questions and remaining risks**")
    for q in pm.open_questions:
        st.markdown(f"- Open: {q}")
    for rk in pm.remaining_risks:
        st.markdown(f"- Risk: {rk}")

with tabs[7]:
    md = render_markdown(pm)
    d1, d2 = st.columns(2)
    d1.download_button("Download Markdown", md, file_name=f"{pm.incident_id}_postmortem.md")
    d2.download_button("Download JSON", pm.model_dump_json(indent=2), file_name=f"{pm.incident_id}_postmortem.json")
    st.caption("PDF export is Phase 11.")
    st.markdown(md)

with tabs[8]:
    st.caption("Independent re-check of this saved report against the original evidence files. "
               "It proves claims are grounded, not that they are true.")
    st.markdown(render_verify(b.check))
    st.markdown("**Validation log** (what the validator changed while generating)")
    st.code("\n".join(pm.validation_log) or "(empty)")
